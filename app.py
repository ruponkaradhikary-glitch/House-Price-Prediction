@st.cache_data
def make_dataset(n=900, seed=42):
    """Create a reproducible demo dataset when no external CSV is supplied."""
    rng = np.random.default_rng(seed)
    area = rng.integers(450, 3501, n)
    bedrooms = np.clip(np.round(area / 650 + rng.normal(0.5, 0.7, n)), 1, 7).astype(int)
    bathrooms = np.clip(np.round(bedrooms * 0.65 + rng.normal(0.4, 0.6, n)), 1, 5).astype(int)
    location = rng.choice(["Urban", "Suburban", "Rural"], n, p=[0.45, 0.35, 0.20])
    age = rng.integers(0, 41, n)
    parking = rng.integers(0, 4, n)
    floor = rng.integers(1, 6, n)
    location_bonus = pd.Series(location).map({"Urban": 22, "Suburban": 12, "Rural": 0}).to_numpy()
    noise = rng.normal(0, 8, n)
    # Price is in lakh rupees. This is synthetic demonstration data, not market data.
    price = (area * 0.035 + bedrooms * 3.2 + bathrooms * 2.1 +
             location_bonus - age * 0.45 + parking * 1.8 + floor * 0.5 + noise)
    price = np.maximum(price, 8)
    return pd.DataFrame({
        "Area (sq ft)": area, "Bedrooms": bedrooms, "Bathrooms": bathrooms,
        "Location": location, "House Age (years)": age, "Parking": parking,
        "Floor": floor, "Price (Lakh)": np.round(price, 2)
    })

@st.cache_resource
def train_models(data):
    features = ["Area (sq ft)", "Bedrooms", "Bathrooms", "Location",
                "House Age (years)", "Parking", "Floor"]
    X, y = data[features], data["Price (Lakh)"]
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, random_state=42
    )
    numeric = ["Area (sq ft)", "Bedrooms", "Bathrooms", "House Age (years)", "Parking", "Floor"]
    categorical = ["Location"]
    preprocessor = ColumnTransformer([
        ("num", Pipeline([("imputer", SimpleImputer(strategy="median")),
                          ("scaler", StandardScaler())]), numeric),
        ("cat", Pipeline([("imputer", SimpleImputer(strategy="most_frequent")),
                          ("onehot", OneHotEncoder(handle_unknown="ignore"))]), categorical)
    ])
    estimators = {
        "Linear Regression": LinearRegression(),
        "Random Forest": RandomForestRegressor(n_estimators=180, random_state=42, min_samples_leaf=2),
        "Gradient Boosting": GradientBoostingRegressor(random_state=42, n_estimators=140, max_depth=2)
    }
    trained, rows = {}, []
    for name, estimator in estimators.items():
        pipe = Pipeline([("preprocessor", preprocessor), ("model", estimator)])
        pipe.fit(X_train, y_train)
        pred = pipe.predict(X_test)
        trained[name] = pipe
        rows.append({
            "Model": name,
            "MAE (Lakh)": mean_absolute_error(y_test, pred),
            "RMSE (Lakh)": mean_squared_error(y_test, pred) ** 0.5,
            "R² Score": r2_score(y_test, pred)
        })
    metrics = pd.DataFrame(rows).sort_values("R² Score", ascending=False).reset_index(drop=True)
    return trained, metrics, X_test, y_test

data = make_dataset()
models, metrics, X_test, y_test = train_models(data)
best_name = metrics.iloc[0]["Model"]
best_model = models[best_name]

